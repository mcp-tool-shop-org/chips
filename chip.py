#!/usr/bin/env python3
"""chip.py — registry helper for studio background-task "chips".

Stdlib only (Python 3). No third-party dependencies.

A "chip" is a spun-off Claude Code session that does one bounded task in the
background and reports back. This tool is the single source of truth for which
chips exist, what branch each one owns, and whether its result has been
reconciled. See README.md for the full chip discipline.

Storage:
  registry.jsonl   machine-readable, one JSON object per line (the source of truth)
  registry.md      human-readable table, REGENERATED on every mutation (never hand-edit)

Subcommands:
  add      append a new chip row
  update   change one or more fields on an existing chip (by id)
  list     print the registry as a table

Field schema (see README.md):
  id, agreed, intent, branch, base_sha, produced_sha, status, await_plan

Status lifecycle:
  proposed -> agreed -> spawned -> awaiting -> reconciled
"""

import argparse
import json
import os
import sys
from datetime import date

# Make console output safe for non-ASCII (em dashes, etc.) on Windows.
try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass

HERE = os.path.dirname(os.path.abspath(__file__))
JSONL_PATH = os.path.join(HERE, "registry.jsonl")
MD_PATH = os.path.join(HERE, "registry.md")

FIELDS = [
    "id",
    "agreed",
    "intent",
    "branch",
    "base_sha",
    "produced_sha",
    "status",
    "await_plan",
]

STATUSES = ["proposed", "agreed", "spawned", "awaiting", "reconciled"]


def die(msg):
    """Print a structured error to stderr and exit non-zero."""
    print(f"chip.py: error: {msg}", file=sys.stderr)
    sys.exit(1)


def load_rows():
    """Read registry.jsonl into a list of dicts. Returns [] if the file is absent."""
    rows = []
    if not os.path.exists(JSONL_PATH):
        return rows
    with open(JSONL_PATH, "r", encoding="utf-8") as f:
        for lineno, raw in enumerate(f, 1):
            line = raw.strip()
            if not line:
                continue
            try:
                rows.append(json.loads(line))
            except json.JSONDecodeError as exc:
                die(f"registry.jsonl line {lineno} is not valid JSON: {exc}")
    return rows


def _md_cell(value):
    """Escape a value for a single Markdown table cell."""
    s = "" if value is None else str(value)
    return s.replace("|", "\\|").replace("\n", " ").strip()


def render_md(rows):
    """Regenerate registry.md from rows."""
    header = "| " + " | ".join(FIELDS) + " |"
    sep = "| " + " | ".join(["---"] * len(FIELDS)) + " |"
    lines = [
        "# Chip Registry",
        "",
        "_Generated by `chip.py` — do not hand-edit. Use `python chip.py add` /"
        " `python chip.py update <id>` to change rows, then commit both"
        " `registry.jsonl` and `registry.md`._",
        "",
        header,
        sep,
    ]
    for row in rows:
        lines.append("| " + " | ".join(_md_cell(row.get(k, "")) for k in FIELDS) + " |")
    lines.append("")
    with open(MD_PATH, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))


def write_rows(rows):
    """Write rows to registry.jsonl (atomically) and regenerate registry.md."""
    tmp = JSONL_PATH + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as f:
        for row in rows:
            # Known fields first, in schema order; preserve any extras after.
            ordered = {k: row.get(k, "") for k in FIELDS}
            for k, v in row.items():
                if k not in ordered:
                    ordered[k] = v
            f.write(json.dumps(ordered, ensure_ascii=False) + "\n")
    os.replace(tmp, JSONL_PATH)
    render_md(rows)


def _trunc(value, width):
    s = str(value)
    return s if len(s) <= width else s[: width - 3] + "..."


def cmd_list(_args):
    rows = load_rows()
    if not rows:
        print("(registry empty)")
        return
    # Cap the widest free-text columns so the table stays readable in a terminal.
    caps = {"intent": 48, "await_plan": 48}
    widths = {c: len(c) for c in FIELDS}
    display = []
    for row in rows:
        cells = {c: _trunc(row.get(c, ""), caps.get(c, 10_000)) for c in FIELDS}
        display.append(cells)
        for c in FIELDS:
            widths[c] = max(widths[c], len(cells[c]))

    def fmt(cells):
        return "  ".join(str(cells[c]).ljust(widths[c]) for c in FIELDS)

    print(fmt({c: c for c in FIELDS}))
    print("  ".join("-" * widths[c] for c in FIELDS))
    for cells in display:
        print(fmt(cells))


def cmd_add(args):
    rows = load_rows()
    if any(r.get("id") == args.id for r in rows):
        die(f"chip id '{args.id}' already exists; use 'update' instead")
    status = args.status or "proposed"
    if status not in STATUSES:
        die(f"invalid status '{status}'; must be one of: {', '.join(STATUSES)}")
    row = {
        "id": args.id,
        "agreed": args.agreed or date.today().isoformat(),
        "intent": args.intent or "",
        "branch": args.branch or "",
        "base_sha": args.base_sha or "",
        "produced_sha": args.produced_sha or "",
        "status": status,
        "await_plan": args.await_plan or "",
    }
    rows.append(row)
    write_rows(rows)
    print(f"added chip '{row['id']}' (status={status})")


def cmd_update(args):
    rows = load_rows()
    target = next((r for r in rows if r.get("id") == args.id), None)
    if target is None:
        die(f"no chip with id '{args.id}'")
    updates = {
        "agreed": args.agreed,
        "intent": args.intent,
        "branch": args.branch,
        "base_sha": args.base_sha,
        "produced_sha": args.produced_sha,
        "status": args.status,
        "await_plan": args.await_plan,
    }
    changed = []
    for key, value in updates.items():
        if value is None:
            continue
        if key == "status" and value not in STATUSES:
            die(f"invalid status '{value}'; must be one of: {', '.join(STATUSES)}")
        target[key] = value
        changed.append(key)
    if not changed:
        die("nothing to update; pass at least one field flag (e.g. --status)")
    write_rows(rows)
    print(f"updated chip '{args.id}': {', '.join(changed)}")


def _add_field_flags(parser, include_status_default=False):
    parser.add_argument("--agreed", help="date agreed, YYYY-MM-DD (default: today, on add)")
    parser.add_argument("--intent", help="one-line description of the chip's task")
    parser.add_argument("--branch", help="the branch/worktree this chip OWNS")
    parser.add_argument("--base-sha", dest="base_sha", help="SHA the chip branched from")
    parser.add_argument("--produced-sha", dest="produced_sha", help="SHA the chip produced")
    status_help = "lifecycle status: " + " -> ".join(STATUSES)
    if include_status_default:
        status_help += " (default: proposed)"
    parser.add_argument("--status", help=status_help)
    parser.add_argument("--await-plan", dest="await_plan", help="how/when its result is awaited & reconciled")


def build_parser():
    parser = argparse.ArgumentParser(
        prog="chip.py",
        description="Registry helper for studio background-task chips.",
    )
    sub = parser.add_subparsers(dest="command", required=True)

    p_add = sub.add_parser("add", help="append a new chip row")
    p_add.add_argument("--id", required=True, help="unique chip id, e.g. chip-ab12-short-slug")
    _add_field_flags(p_add, include_status_default=True)
    p_add.set_defaults(func=cmd_add)

    p_update = sub.add_parser("update", help="update fields on an existing chip")
    p_update.add_argument("id", help="id of the chip to update")
    _add_field_flags(p_update)
    p_update.set_defaults(func=cmd_update)

    p_list = sub.add_parser("list", help="print the registry as a table")
    p_list.set_defaults(func=cmd_list)

    return parser


def main(argv=None):
    parser = build_parser()
    args = parser.parse_args(argv)
    args.func(args)


if __name__ == "__main__":
    main()
